#!/usr/bin/env bash
# Writes Package.swift for a release: a binary target that points at the
# Bifrost.xcframework.zip asset of that release.
#
#   scripts/update-package-swift.sh <tag> <checksum>
#
# <checksum> is the SHA-256 of the zip, as printed by `swift package compute-checksum`
# (same value as `shasum -a 256`). Run by .github/workflows/release.yml.
set -euo pipefail

TAG="${1:?usage: $0 <tag> <checksum>}"
SUM="${2:?usage: $0 <tag> <checksum>}"
[[ "$TAG" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "error: tag must look like v1.2.3" >&2; exit 1; }
[[ "$SUM" =~ ^[0-9a-f]{64}$ ]] || { echo "error: checksum must be 64 hex characters" >&2; exit 1; }
REPO="${GITHUB_REPOSITORY:-MichaelBMF/bifrost}"

cd "$(dirname "$0")/.."
cat > Package.swift <<SWIFT
// swift-tools-version:5.9
// Generated by scripts/update-package-swift.sh for ${TAG}. Do not edit by hand.
import PackageDescription

let package = Package(
    name: "Bifrost",
    platforms: [.iOS(.v16)],
    products: [
        .library(name: "Bifrost", targets: ["Bifrost"]),
    ],
    targets: [
        .binaryTarget(
            name: "Bifrost",
            url: "https://github.com/${REPO}/releases/download/${TAG}/Bifrost.xcframework.zip",
            checksum: "${SUM}"
        ),
    ]
)
SWIFT
echo "Package.swift -> ${TAG} (${SUM})"
